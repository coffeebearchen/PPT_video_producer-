import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {computeEnergy,energyAt} from '../engines/vibemotion/renderer/src/avatar/energy.ts';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),renderer=path.join(root,'engines/vibemotion/renderer'),out=path.join(renderer,'out/round5');
const track=JSON.parse(fs.readFileSync(path.join(renderer,'public/audio/round5/energy.json'),'utf8'));
assert.equal(track.values.length,360);assert.equal(energyAt(track,-1),0);assert.equal(energyAt(track,12000),0);
assert.ok(Math.max(...track.values)>.8);
assert.ok(track.rms.some(r=>r<track.silenceFloor));
assert.ok(track.rms.every((r,i)=>r>track.silenceFloor||track.values[i]===0));
assert.ok(computeEnergy(new Float32Array(16000),16000).values.every(v=>v===0));
const again=execFileSync('ffmpeg',['-v','error','-i',path.join(renderer,'public/audio/round5/narration.wav'),'-f','f32le','-ar','16000','-ac','1','pipe:1']);
assert.deepEqual(computeEnergy(new Float32Array(again.buffer.slice(again.byteOffset,again.byteOffset+again.length)),16000).values,track.values);
const boxes={avatar:{x:770,y:1320,w:160,h:144},diagram:{x:140,y:530,w:800,h:780},takeaway:{x:150,y:1360,w:590,h:56},source:{x:140,y:1470,w:800,h:60},subtitles:{x:140,y:1550,w:800,h:100},cta:{x:650,y:1680,w:290,h:40}};
const a=boxes.avatar;
assert.ok(a.x>=108&&a.y>=192&&a.x+a.w<=972&&a.y+a.h<=1728);
for(const [name,b] of Object.entries(boxes))if(name!=='avatar')assert.ok(!(a.x<b.x+b.w&&a.x+a.w>b.x&&a.y<b.y+b.h&&a.y+a.h>b.y),`Avatar overlaps ${name}`);
const video=path.join(out,'avatar.mp4');
const media=JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json',video],{encoding:'utf8'}));
const v=media.streams.find(s=>s.codec_type==='video'),audio=media.streams.find(s=>s.codec_type==='audio');
assert.equal(v.width,1080);assert.equal(v.height,1920);assert.equal(v.r_frame_rate,'30/1');assert.equal(v.codec_name,'h264');assert.equal(audio.codec_name,'aac');assert.equal(Number(v.nb_frames),360);
const frames=[0,14,60,100,150,216,300,357];
const ff=args=>execFileSync('ffmpeg',['-y','-hide_banner','-loglevel','error',...args]);
const selection=`select='${frames.map(n=>`eq(n,${n})`).join('+')}'`;
ff(['-i',video,'-vf',`${selection},scale=270:480,tile=4x2`,'-frames:v','1',path.join(out,'contact-sheet.png')]);
ff(['-i',video,'-vf',`${selection},crop=160:144:770:1320,scale=320:288,tile=4x2`,'-frames:v','1',path.join(out,'mouth-detail.png')]);
ff(['-i',video,'-f','null','-']);
const result={durationSeconds:media.format.duration,video:v.codec_name,audio:audio.codec_name,resolution:[v.width,v.height],fps:30,frames:360,mode:'local audio-energy simulation, not phoneme alignment',energyDeterministic:'passed',silentFramesClosed:'passed',allSilentAudioClosed:'passed',boundsAndReservedAreas:'passed',decode:'passed',contactSheetFrames:frames,mouthEnergyAtFrames:frames.map(i=>track.values[i]),boxes};
fs.writeFileSync(path.join(out,'validation.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
